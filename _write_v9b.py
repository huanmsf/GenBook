"""write_v9b.py — 通过 json.dumps 生成复杂转义，规避多层引号问题"""
import pathlib, json

def q(s):
    """用 json.dumps 安全转义单引号字符串中的特殊字符，去掉外层双引号"""
    return json.dumps(s)[1:-1]  # 去掉 json 的外层 ""

esc_map_items = [
    (r"\\",  r"\\\\"),
    ("#",    r"\#"),
    ("@",    r"\@"),
    ("<",    r"\<"),
    (">",    r"\>"),
    ("*",    r"\*"),
    ("`",    r"\`"),
    ("$",    r"\$"),
    ("=",    r"\="),
    ("~",    r"\~"),
    ("'",    r"\'"),
    ('"',    r'\"'),
    ("[",    r"\["),
    ("]",    r"\]"),
]

esc_lines = ["_ESC: dict[str, str] = {"]
for k, v in esc_map_items:
    esc_lines.append(f"    {k!r}: {v!r},")
esc_lines.append("}")

parts = []

parts.append('"""typst_writer.py v9 — 字符坐标重分列 + #place 绝对定位竖排。"""')
parts.append("from __future__ import annotations")
parts.append("import os")
parts.append("from modules.page_model import PageData, CharData")
parts.append("")
parts.append("")
parts.append("def build_typ_output_path(pdf_path: str) -> str:")
parts.append("    root, _ = os.path.splitext(pdf_path)")
parts.append("    return root + '.typ'")
parts.append("")
parts.append("")
parts.extend(esc_lines)
parts.append("")
parts.append("")
parts.append("def _escape_typst(text: str) -> str:")
parts.append("    return ''.join(_ESC.get(ch, ch) for ch in text)")
parts.append("")
parts.append("")
parts.append("def _px_to_pt(px: float, dpi: int) -> float:")
parts.append("    return px * 72.0 / dpi")
parts.append("")
parts.append("")
parts.append("def _mm_to_pt(mm: float) -> float:")
parts.append("    return mm * 72.0 / 25.4")
parts.append("")
parts.append("")
parts.append("def _to_chinese_numeral(num: int) -> str:")
parts.append("    digits = '零一二三四五六七八九'")
parts.append("    if num <= 0:  return digits[0]")
parts.append("    if num < 10:  return digits[num]")
parts.append("    if num == 10: return '十'")
parts.append("    if num < 20:  return '十' + digits[num % 10]")
parts.append("    tens, ones = divmod(num, 10)")
parts.append("    return digits[tens] + '十' + (digits[ones] if ones else '')")
parts.append("")
parts.append("")
parts.append("def _recluster_chars(")
parts.append("    chars: list[CharData],")
parts.append("    dpi: int,")
parts.append("    gap_px: int = 35,")
parts.append(") -> list[dict]:")
parts.append('    """按字符 cx 坐标聚类，重建列结构（从右到左，source_order=1=最右）。"""')
parts.append("    if not chars:")
parts.append("        return []")
parts.append("    tagged = []")
parts.append("    for c in chars:")
parts.append("        bx1, by1, bx2, by2 = c.bbox")
parts.append("        cx = (bx1 + bx2) / 2.0")
parts.append("        tagged.append((cx, c))")
parts.append("    tagged.sort(key=lambda t: -t[0])  # 右→左")
parts.append("    clusters: list[list] = []")
parts.append("    cur_sum = tagged[0][0]; cur_cnt = 1; cur_grp = [tagged[0]]")
parts.append("    for cx, c in tagged[1:]:")
parts.append("        if abs(cx - cur_sum / cur_cnt) <= gap_px:")
parts.append("            cur_grp.append((cx, c)); cur_sum += cx; cur_cnt += 1")
parts.append("        else:")
parts.append("            clusters.append(cur_grp)")
parts.append("            cur_grp = [(cx, c)]; cur_sum = cx; cur_cnt = 1")
parts.append("    clusters.append(cur_grp)")
parts.append("    result = []")
parts.append("    for i, grp in enumerate(clusters):")
parts.append("        col_cx = sum(x for x, _ in grp) / len(grp)")
parts.append("        col_chars = sorted([c for _, c in grp], key=lambda c: c.bbox[1])")
parts.append("        result.append({'source_order': i + 1,")
parts.append("                       'col_cx_px': col_cx,")
parts.append("                       'chars': col_chars})")
parts.append("    return result")
parts.append("")
parts.append("")
parts.append("def _classify(n: int, col_cx_px: float, page_w_px: int) -> str:")
parts.append("    if n == 0: return 'empty'")
parts.append("    if col_cx_px >= page_w_px * 0.85 and n <= 8: return 'title'")
parts.append("    if n <= 4: return 'note'")
parts.append("    return 'main'")
parts.append("")
parts.append("")
parts.append("def _build_header(config: dict) -> str:")
parts.append("    ff  = config.get('font_family', 'STKaiTi')")
parts.append("    fs  = float(config.get('font_size', 12))")
parts.append("    ns  = float(config.get('note_font_size', 8))")
parts.append("    g   = config.get('guji_layout', {})")
parts.append("    paper       = g.get('paper', 'jis-b5')")
parts.append("    tmpl        = g.get('template', 'blank')")
parts.append("    tian_tou    = _mm_to_pt(float(g.get('tian_tou_mm',    25)))")
parts.append("    di_jiao     = _mm_to_pt(float(g.get('di_jiao_mm',     20)))")
parts.append("    zhuang_ding = _mm_to_pt(float(g.get('zhuang_ding_mm', 20)))")
parts.append("    shu_kou     = _mm_to_pt(float(g.get('shu_kou_mm',     15)))")
parts.append("    rows = [")
parts.append("        '// GenBook v9 — 字符坐标重分列 + place 绝对定位竖排',")
parts.append("        f'// 模板：{tmpl}',")
parts.append("        '',")
parts.append("        '#set text(',")
parts.append("        f'  font: (\"{ff}\", \"Noto Serif CJK TC\", \"SimSun\"),',")
parts.append("        f'  size: {fs:.1f}pt,',")
parts.append("        '  lang: \"zh\"',")
parts.append("        ')',")
parts.append("        '#set par(leading: 0pt, spacing: 0pt)',")
parts.append("        f'#let _cw = {fs:.1f}pt',")
parts.append("        f'#let _ns = {ns:.1f}pt',")
parts.append("        '#set page(',")
parts.append("        f'  paper: \"{paper}\",',")
parts.append("        f'  margin: (top: {tian_tou:.1f}pt, bottom: {di_jiao:.1f}pt,',")
parts.append("        f'           left: {shu_kou:.1f}pt, right: {zhuang_ding:.1f}pt)',")
parts.append("        ')',")
parts.append("        '',")
parts.append("        '// vcol: 逐字竖排',")
parts.append("        '#let vcol(s, cw: _cw) = {',")
parts.append("        '  for c in s.clusters() {',")
parts.append("        '    box(width: cw, height: cw)[#align(center + horizon)[#c]]',")
parts.append("        '  }',")
parts.append("        '}',")
parts.append("        '',")
parts.append("    ]")
parts.append("    return '\\n'.join(rows)")
parts.append("")
parts.append("")
parts.append("def _build_page_block(page: PageData, assets_dir: str,")
parts.append("                      page_index: int, config: dict) -> str:")
parts.append("    g    = config.get('guji_layout', {})")
parts.append("    fs   = float(config.get('font_size', 12))")
parts.append("    ns   = float(config.get('note_font_size', 8))")
parts.append("    tmpl = g.get('template', 'blank')")
parts.append("    show_num  = bool(g.get('show_page_num', True))")
parts.append("    num_style = g.get('page_num_style', 'chinese')")
parts.append("    htitle    = g.get('header_title', '')")
parts.append("    hvol      = g.get('header_volume', '')")
parts.append("    dpi       = page.dpi")
parts.append("")
parts.append("    tian_tou    = _mm_to_pt(float(g.get('tian_tou_mm',    25)))")
parts.append("    di_jiao     = _mm_to_pt(float(g.get('di_jiao_mm',     20)))")
parts.append("    zhuang_ding = _mm_to_pt(float(g.get('zhuang_ding_mm', 20)))")
parts.append("    shu_kou     = _mm_to_pt(float(g.get('shu_kou_mm',     15)))")
parts.append("    page_w_pt   = _px_to_pt(page.orig_width_px,  dpi)")
parts.append("    page_h_pt   = _px_to_pt(page.orig_height_px, dpi)")
parts.append("    banxin_w    = page_w_pt  - zhuang_ding - shu_kou")
parts.append("    banxin_h    = page_h_pt  - tian_tou    - di_jiao")
parts.append("")
parts.append("    all_chars: list[CharData] = []")
parts.append("    for col in page.text_columns:")
parts.append("        all_chars.extend(col.chars)")
parts.append("    recs = _recluster_chars(all_chars, dpi, gap_px=35)")
parts.append("")
parts.append("    lns: list[str] = []")
parts.append("    if page_index > 0:")
parts.append("        lns += ['#pagebreak()', '']")
parts.append("")
parts.append("    side = '右→左' if page.page_num % 2 == 1 else '左→右'")
parts.append("    lns.append(")
parts.append("        f'// === 第 {page.page_num} 页  {tmpl}'")
parts.append("        f'  重分列={len(recs)}列'")
parts.append("        f'  原PDF={page_w_pt:.0f}x{page_h_pt:.0f}pt'")
parts.append("        f'  版心={banxin_w:.0f}x{banxin_h:.0f}pt  装订={side} ==='")
parts.append("    )")
parts.append("    lns.append('')")
parts.append("")
parts.append("    if htitle or hvol:")
parts.append("        lns.append(f'#align(center)[{_escape_typst((htitle + \" \" + hvol).strip())}]')")
parts.append("        lns.append('')")
parts.append("")
parts.append("    lns.append(f'#block(width: {banxin_w:.1f}pt, height: {banxin_h:.1f}pt)[')")
parts.append("")
parts.append("    for col in recs:")
parts.append("        n       = len(col['chars'])")
parts.append("        cx_px   = col['col_cx_px']")
parts.append("        order   = col['source_order']")
parts.append("        ctype   = _classify(n, cx_px, page.orig_width_px)")
parts.append("        cw_expr = '_ns' if ctype == 'note' else '_cw'")
parts.append("        cw_val  = ns    if ctype == 'note' else fs")
parts.append("        h_pt    = n * cw_val")
parts.append("        right_off = (page.orig_width_px - cx_px) / page.orig_width_px * banxin_w")
parts.append("        x_left    = banxin_w - right_off - cw_val / 2")
parts.append("        text = _escape_typst(''.join(c.text for c in col['chars']))")
parts.append("        lns.append(")
parts.append("            f'  // 列{order:2d}: {ctype:5s}  字数={n:3d}'")
parts.append("            f'  cx={cx_px:.0f}px  x_left={x_left:.1f}pt'")
parts.append("        )")
parts.append("        inner = f'box(width: {cw_expr}, height: {h_pt:.1f}pt)'")
parts.append("        if text.strip():")
parts.append("            inner += f'[#vcol(\"{text}\", cw: {cw_expr})]'")
parts.append("        else:")
parts.append("            inner += '[]'")
parts.append("        lns.append(f'  #place(top + left, dx: {x_left:.1f}pt, dy: 0pt)[{inner}]')")
parts.append("")
parts.append("    lns.append(']')")
parts.append("    lns.append('')")
parts.append("")
parts.append("    if show_num:")
parts.append("        num = _to_chinese_numeral(page.page_num) if num_style == 'chinese' else str(page.page_num)")
parts.append("        lns.append(f'#align(center)[{num}]')")
parts.append("        lns.append('')")
parts.append("")
parts.append("    for ii, ir in enumerate(page.image_regions):")
parts.append("        fn   = f'p{page.page_num}_img_{ii+1:03d}.png'")
parts.append("        fabs = os.path.join(assets_dir, fn)")
parts.append("        os.makedirs(assets_dir, exist_ok=True)")
parts.append("        open(fabs, 'wb').write(ir.image_bytes)")
parts.append("        iw = _px_to_pt(ir.bbox[2]-ir.bbox[0], dpi)")
parts.append("        ih = _px_to_pt(ir.bbox[3]-ir.bbox[1], dpi)")
parts.append("        rel = os.path.join('assets', fn).replace('\\\\', '/')")
parts.append("        lns.append(f'#image(\"{rel}\", width: {iw:.1f}pt, height: {ih:.1f}pt)')")
parts.append("        lns.append('')")
parts.append("")
parts.append("    return '\\n'.join(lns)")
parts.append("")
parts.append("")
parts.append("def create_typst(pages: list[PageData], output_path: str, config: dict) -> None:")
parts.append("    os.makedirs(os.path.dirname(output_path) or '.', exist_ok=True)")
parts.append("    assets_dir = os.path.join(os.path.dirname(output_path) or '.', 'assets')")
parts.append("    parts2 = [_build_header(config)]")
parts.append("    for idx, page in enumerate(pages):")
parts.append("        parts2.append(_build_page_block(page, assets_dir, idx, config))")
parts.append("    with open(output_path, 'w', encoding='utf-8') as f:")
parts.append("        f.write('\\n'.join(parts2))")
parts.append("")

content = "\n".join(parts)
pathlib.Path("modules/typst_writer.py").write_text(content, encoding="utf-8")
print(f"written {content.count(chr(10))} lines")
import ast
ast.parse(content)
print("syntax OK")
